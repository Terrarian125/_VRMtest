#pragma once

#include <cstdint>
#include <string>
#include <vector>

// VRM.h はマクロによって対応するVRM仕様を有効化する。
// 今回は 0.x と 1.0 の両方を扱えるようにする。
#define USE_VRMC_VRM_0_0
#define USE_VRMC_VRM_1_0

#include <VRMC/VRM.h>


//==================================================
// VRMModel
//
// VRMファイルの読み込み・VRM情報管理を担当する。
//
//
// 現段階では、
// ・VRMファイル読み込み
// ・VRM 0.x / 1.0 判定
// ・メタ情報取得
// ・Humanoid情報取得
//
// までを担当する。
//
// 実際のメッシュ描画・スキニング・アニメーションは
// 今後ここへ追加する。
//==================================================
class VRMModel
{
public:

	//==================================================
	// VRM仕様
	//==================================================
	enum class Version
	{
		Unknown,

		VRM_0_X,

		VRM_1_0
	};


public:

	//==================================================
	// コンストラクタ / デストラクタ
	//==================================================
	VRMModel();
	~VRMModel();


	//==================================================
	// VRM読み込み
	//
	// 成功 : true
	// 失敗 : false
	//==================================================
	bool Load(const std::string& filePath);


	//==================================================
	// 解放
	//==================================================
	void Release();


	//==================================================
	// 読み込み済みか
	//==================================================
	bool IsLoaded() const;


	//==================================================
	// VRMバージョン取得
	//==================================================
	Version GetVersion() const;


	//==================================================
	// VRM 1.0情報取得
	//
	// VRM 1.0ではnullptrになる場合がある。
	//==================================================
	const VRMC_VRM_1_0::Vrm* GetVRM1() const;


	//==================================================
	// VRM 0.x情報取得
	//
	// VRM 0.xではnullptrになる場合がある。
	//==================================================
	const VRMC_VRM_0_0::Vrm* GetVRM0() const;


	//==================================================
	// モデル名取得
	//==================================================
	std::string GetModelName() const;


	//==================================================
	// 作者取得
	//==================================================
	std::string GetAuthorName() const;


	//==================================================
	// Humanoidボーン数取得
	//==================================================
	size_t GetHumanoidBoneCount() const;


	//==================================================
	// glTFノード数取得
	//==================================================
	size_t GetNodeCount() const;


	//==================================================
	// glTFメッシュ数取得
	//==================================================
	size_t GetMeshCount() const;


	//==================================================
	// 読み込みエラー内容取得
	//==================================================
	const std::string& GetLastError() const;


private:

	//==================================================
	// VRM 0.x読み込み
	//==================================================
	bool LoadVRM0(
		const nlohmann::json& extensions);


	//==================================================
	// VRM 1.0読み込み
	//==================================================
	bool LoadVRM1(
		const nlohmann::json& extensions);


	//==================================================
	// エラー設定
	//==================================================
	void SetError(
		const std::string& message);


private:

	//==================================================
	// 読み込み状態
	//==================================================
	bool m_loaded;


	//==================================================
	// VRM仕様
	//==================================================
	Version m_version;


	//==================================================
	// 最後に読み込んだファイル
	//==================================================
	std::string m_filePath;


	//==================================================
	// エラー内容
	//==================================================
	std::string m_lastError;


	//==================================================
	// glTF情報
	//==================================================
	size_t m_nodeCount;
	size_t m_meshCount;


	//==================================================
	// VRM 0.x
	//==================================================
	VRMC_VRM_0_0::Vrm m_vrm0;


	//==================================================
	// VRM 1.0
	//==================================================
	VRMC_VRM_1_0::Vrm m_vrm1;
};