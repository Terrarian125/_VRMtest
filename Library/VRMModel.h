#pragma once

#include <DxLib.h>

#include <cstdint>
#include <string>
#include <vector>

#define USE_VRMC_VRM_0_0
#define USE_VRMC_VRM_1_0

#include <VRMC/VRM.h>
#include <fx/gltf.h>


//==================================================
// VRMModel
//==================================================
// VRMファイルの読み込み、解析、描画を行う。
//==================================================
class VRMModel
{
public:

	//==================================================
	// VRMバージョン
	//==================================================
	enum class Version
	{
		Unknown,
		VRM_0_X,
		VRM_1_0
	};


private:

	//==================================================
	// 描画用プリミティブ
	//==================================================
	struct RenderPrimitive
	{
		std::vector<DxLib::VERTEX3D> vertices;
		std::vector<unsigned short> indices;

		int materialIndex;

		int nodeIndex;
	};


public:

	//==================================================
	// コンストラクタ
	//==================================================
	VRMModel();


	//==================================================
	// デストラクタ
	//==================================================
	~VRMModel();


	//==================================================
	// VRM読み込み
	//==================================================
	bool Load(
		const std::string& filePath);


	//==================================================
	// 解放
	//==================================================
	void Release();


	//==================================================
	// 読み込み済みか
	//==================================================
	bool IsLoaded() const;


	//==================================================
	// VRMバージョン取得
	//==================================================
	Version GetVersion() const;


	//==================================================
	// VRM 1.0情報取得
	//==================================================
	const VRMC_VRM_1_0::Vrm* GetVRM1() const;


	//==================================================
	// VRM 0.x情報取得
	//==================================================
	const VRMC_VRM_0_0::Vrm* GetVRM0() const;


	//==================================================
	// モデル名取得
	//==================================================
	std::string GetModelName() const;


	//==================================================
	// 作者名取得
	//==================================================
	std::string GetAuthorName() const;


	//==================================================
	// Humanoidボーン数取得
	//==================================================
	size_t GetHumanoidBoneCount() const;


	//==================================================
	// glTFノード数取得
	//==================================================
	size_t GetNodeCount() const;


	//==================================================
	// glTFメッシュ数取得
	//==================================================
	size_t GetMeshCount() const;


	//==================================================
	// 描画プリミティブ数取得
	//==================================================
	size_t GetRenderPrimitiveCount() const;


	//==================================================
	// エラー取得
	//==================================================
	const std::string& GetLastError() const;


	//==================================================
	// 描画
	//==================================================
	void Draw(
		float scale,
		DxLib::VECTOR position,
		float rotationY);


private:

	//==================================================
	// VRM 0.x読み込み
	//==================================================
	bool LoadVRM0(
		const nlohmann::json& extensions);


	//==================================================
	// VRM 1.0読み込み
	//==================================================
	bool LoadVRM1(
		const nlohmann::json& extensions);


	//==================================================
	// glTF描画データ生成
	//==================================================
	bool BuildRenderData();


	//==================================================
	// プリミティブ描画データ生成
	//==================================================
	bool BuildPrimitive(
		const fx::gltf::Primitive& primitive,
		int nodeIndex,
		RenderPrimitive& output);


	//==================================================
	// アクセサからVec3を取得
	//==================================================
	bool ReadVec3Accessor(
		int accessorIndex,
		std::vector<DxLib::VECTOR>& output) const;


	//==================================================
	// アクセサからVec2を取得
	//==================================================
	bool ReadVec2Accessor(
		int accessorIndex,
		std::vector<std::pair<float, float>>& output) const;


	//==================================================
	// インデックスアクセサ取得
	//==================================================
	bool ReadIndexAccessor(
		int accessorIndex,
		std::vector<unsigned short>& output) const;


	//==================================================
	// エラー設定
	//==================================================
	void SetError(
		const std::string& message);


private:

	//==================================================
	// 読み込み状態
	//==================================================
	bool m_loaded;


	//==================================================
	// VRMバージョン
	//==================================================
	Version m_version;


	//==================================================
	// ファイルパス
	//==================================================
	std::string m_filePath;


	//==================================================
	// エラー内容
	//==================================================
	std::string m_lastError;


	//==================================================
	// glTF情報
	//==================================================
	size_t m_nodeCount;
	size_t m_meshCount;


	//==================================================
	// glTF本体
	//==================================================
	fx::gltf::Document m_document;


	//==================================================
	// VRM 0.x
	//==================================================
	VRMC_VRM_0_0::Vrm m_vrm0;


	//==================================================
	// VRM 1.0
	//==================================================
	VRMC_VRM_1_0::Vrm m_vrm1;


	//==================================================
	// DxLib描画用データ
	//==================================================
	std::vector<RenderPrimitive> m_renderPrimitives;
};